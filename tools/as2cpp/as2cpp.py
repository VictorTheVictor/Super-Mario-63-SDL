#!/usr/bin/env python3
"""as2cpp: transpiles Super Mario 63's ActionScript 2 (from the XFL source) into C++
registered against the SWF locations it was compiled to.

Usage: as2cpp.py --xfl DIR --swf FILE --out DIR

Writes DIR/scripts_*.cpp, DIR/scripts.cpp (registerScripts) and DIR/REPORT.txt."""

import argparse
import glob
import os
import re
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from emit import EmitError, emit_handlers, emit_script  # noqa: E402
from mapper import Mapper  # noqa: E402
from parser import ParseError, parse  # noqa: E402
from swf import Swf  # noqa: E402
from xfl import Document  # noqa: E402

HEADER = """\
// GENERATED by tools/as2cpp from the ActionScript in the Super Mario 63 XFL source
// (runouw, https://github.com/runouw/Super-Mario-63). This is a translation of that code;
// the upstream repository has no license file, so do not publish it without permission.
//
// Each function is one frame script or event handler; the comment above it names the
// symbol, layer and frame it came from in the Flash library.
"""

MAX_LINES = 4000


def group_key(origin):
    owner = origin.split(" / layer")[0]
    if owner == "<main>":
        return "main"
    first = owner.split("/")[0].strip()
    key = re.sub(r"[^a-z0-9]+", "_", first.lower()).strip("_")
    return key or "misc"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--xfl", required=True)
    ap.add_argument("--swf", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    t0 = time.time()

    doc = Document(args.xfl)
    swf = Swf(args.swf)
    mapper = Mapper(doc, swf).run()

    groups = {}       # key -> [(sort key, lines)]
    registrations = {}  # key -> [registration lines]
    errors, unsupported = [], []
    counts = {"frame": 0, "clip": 0, "button": 0, "handlers": 0}

    for r in sorted(mapper.results, key=lambda r: (r.origin, r.key)):
        key = group_key(r.origin)
        try:
            program = parse(r.source)
            if r.kind == "frame":
                sid, action = r.key
                name = f"frame_{sid}_{action}"
                lines, unsup = emit_script(program, name, r.origin)
                regs = [f"registerFrameScript({sid}, {action}, {name});"]
                chunks = [lines]
            else:
                button = r.kind == "button"
                base = f"button_{r.key[0]}" if button else f"clip_{r.key[0]}_{r.key[1]}"
                handlers, unsup = emit_handlers(program, base, r.origin, button)
                chunks, regs = [], []
                for fn_name, mask, lines in handlers:
                    chunks.append(lines)
                    if button:
                        regs.append(f"registerButtonAction({r.key[0]}, {mask}, {fn_name});")
                    else:
                        regs.append(f"registerClipEvent({r.key[0]}, {r.key[1]}, {mask}, {fn_name});")
                counts["handlers"] += len(handlers)
            counts[r.kind] += 1
        except (ParseError, EmitError, RecursionError) as e:
            errors.append((r.origin, str(e)))
            continue
        unsupported += [(r.origin, u) for u in unsup]
        for lines in chunks:
            groups.setdefault(key, []).append(lines)
        registrations.setdefault(key, []).extend(regs)

    os.makedirs(args.out, exist_ok=True)
    for old in glob.glob(os.path.join(args.out, "scripts_*.cpp")):
        os.remove(old)

    files = []
    for key in sorted(groups):
        chunk, chunk_regs, part = [], [], 1
        items = groups[key]
        regs = registrations[key]
        # Split large groups; registrations follow their functions.
        reg_iter = iter(regs)
        per_item_regs = []
        for lines in items:
            n = sum(1 for l in lines if l.startswith("void "))
            per_item_regs.append([next(reg_iter) for _ in range(n)])
        size = 0
        for lines, rl in zip(items, per_item_regs):
            if size + len(lines) > MAX_LINES and chunk:
                files.append((f"{key}_{part}", chunk, chunk_regs))
                chunk, chunk_regs, size, part = [], [], 0, part + 1
            chunk.append(lines)
            chunk_regs.extend(rl)
            size += len(lines) + 1
        if chunk:
            files.append((f"{key}_{part}" if part > 1 else key, chunk, chunk_regs))

    total_lines = 0
    for name, chunk, regs in files:
        out = [HEADER, '#include "game/Prelude.h"', "", "namespace game {", "namespace {", ""]
        for lines in chunk:
            out.extend(lines)
            out.append("")
        out += ["}  // namespace", "", f"void register_{name}() {{"]
        out += ["    " + r for r in regs]
        out += ["}", "", "}  // namespace game", ""]
        text = "\n".join(out)
        total_lines += text.count("\n")
        with open(os.path.join(args.out, f"scripts_{name}.cpp"), "w", encoding="utf-8") as f:
            f.write(text)

    with open(os.path.join(args.out, "scripts.cpp"), "w", encoding="utf-8") as f:
        f.write(HEADER + '\n#include "game/Scripts.h"\n\nnamespace game {\n\n')
        for name, _, _ in files:
            f.write(f"void register_{name}();\n")
        f.write("\nvoid registerScripts() {\n")
        for name, _, _ in files:
            f.write(f"    register_{name}();\n")
        f.write("}\n\n}  // namespace game\n")

    low = [r for r in mapper.results if r.score < 0.9]
    with open(os.path.join(args.out, "REPORT.txt"), "w", encoding="utf-8") as f:
        f.write("as2cpp report\n=============\n\n")
        f.write(f"frame scripts: {counts['frame']}, instance scripts: {counts['clip']} "
                f"({counts['handlers']} handlers), button scripts: {counts['button']}\n")
        f.write(f"files: {len(files)}, lines: {total_lines}\n\n")
        f.write(f"Translation errors ({len(errors)}):\n")
        for o, e in errors:
            f.write(f"  {o}\n    {e}\n")
        f.write(f"\nUnsupported constructs ({len(unsupported)}):\n")
        for o, u in unsupported:
            f.write(f"  {u}   [{o}]\n")
        f.write(f"\nMapping problems ({len(mapper.problems)}):\n")
        for o, p in mapper.problems:
            f.write(f"  {p}   [{o}]\n")
        f.write(f"\nLow bytecode verification ({len(low)}; often constant-folded strings):\n")
        for r in low:
            f.write(f"  {r.score:.2f} {r.kind} {r.key}   [{r.origin}]\n")
        f.write(f"\nScripts in library symbols that are not in the SWF: {mapper.unreachable_scripts()}\n")

    print(f"as2cpp: {counts['frame']} frame + {counts['clip']} instance + {counts['button']} button "
          f"scripts -> {len(files)} files, {total_lines} lines; {len(errors)} errors, "
          f"{len(unsupported)} unsupported, {len(mapper.problems)} mapping problems "
          f"({time.time() - t0:.1f} s)")


if __name__ == "__main__":
    main()
