#!/usr/bin/env python3
"""Writes src/EdgeLinks.cpp: the courses' left/right warps and where they lead.

A course's BackGFX script tests hidden boxes named warp1, warp2, ... against Mario and,
for the one he touched (`warpnum == N`), calls
    _root.changecourse("righttransition2", "1-2", camX, camY, marioX, marioY)
Mario then starts at (marioX, marioY) in the target's level-local coordinates. Some warps
keep his height instead: marioY is `Char._y - BackGFX._y + K` (his height in this course
plus K). The port's edge fill (src/EdgeFill.cpp) uses this to draw the next course part
beyond a level edge that leads into it.

usage: tools/edge_links.py   (from the repository root)
"""
import glob
import re

FUNC = re.compile(r'^void (?:frame|clip)_(\d+)_\d+(?:_\d+)?\(Activation& scope\) \{$')
WARP = re.compile(r'warpnum"\] == (\d+)|scope\.self\["warp(\d+)"\]\["hitTest"\]')
CALL = re.compile(r'changecourse"\]\("((?:left|right)transition\w*)", "([^"]+)", (.*)\);')
KEEP_Y = re.compile(r'^_root\["Course"\]\["Char"\]\["_y"\] - _root\["Course"\]\["BackGFX"\]\["_y"\]\s*([+-]\s*\d+(?:\.\d+)?)?$')


def split_args(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch == ',' and depth == 0:
            out.append(cur.strip())
            cur = ''
            continue
        depth += ch in '(['
        depth -= ch in ')]'
        cur += ch
    out.append(cur.strip())
    return out


def number(s):
    try:
        return float(s)
    except ValueError:
        return None


links = {}
for path in sorted(glob.glob('src/game/generated/*.cpp')):
    sprite, warp = None, None
    for line in open(path, encoding='utf-8', errors='replace'):
        m = FUNC.match(line.rstrip())
        if m:
            sprite, warp = int(m.group(1)), None
            continue
        if sprite is None:
            continue
        m = WARP.search(line)
        if m:
            warp = int(m.group(1) or m.group(2))
        m = CALL.search(line)
        if not m or warp is None:
            continue
        args = split_args(m.group(3))
        if len(args) < 4:
            continue
        x, y = number(args[2]), number(args[3])
        keep = KEEP_Y.match(args[3])
        links[(sprite, warp)] = (m.group(1).startswith('right'), m.group(2), x, y,
                                 keep is not None, float((keep.group(1) or '0').replace(' ', '')) if keep else 0.0)

with open('src/EdgeLinks.cpp', 'w') as out:
    out.write('// Generated by tools/edge_links.py from the courses\' warp scripts (src/game/generated):\n'
              '// which hidden warp box of which BackGFX sprite leads left/right into which course part,\n'
              '// and where Mario starts there. Do not edit.\n'
              '#include "EdgeFill.h"\n\n#include <cmath>\n\n'
              'const std::vector<EdgeLink>& edgeLinks() {\n'
              '    static const std::vector<EdgeLink> links = {\n')
    for (sprite, warp), (right, course, x, y, keep, shift) in sorted(links.items()):
        out.write(f'        {{{sprite}, {warp}, {str(right).lower()}, "{course}", {x if x is not None else "NAN"}, '
                  f'{y if y is not None else "NAN"}, {str(keep).lower()}, {shift}}},\n')
    out.write('    };\n    return links;\n}\n')
print(f'{len(links)} left/right warps -> src/EdgeLinks.cpp')
