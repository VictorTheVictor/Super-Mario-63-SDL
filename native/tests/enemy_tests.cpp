#include "enemies.hpp"
#include <stdexcept>
#include <iostream>
void require(bool ok, const char* message) { if (!ok) throw std::runtime_error(message); }
int main() {
    try {
        sm63::Terrain terrain;
        sm63::Player player;
        sm63::Enemies enemies;
        require(enemies.actors.size()==6,"Original six Goomba placements required");
        player.x=-100; player.y=190;
        for (int i=0;i<500;++i) for (auto& enemy:enemies.actors) {
            enemy.tick(terrain,player);
            require(!terrain.body(enemy.x,enemy.y,10,25),"Goomba embedded in terrain");
        }
        sm63::Enemy stomp(100,190);
        player.reset(); player.x=100; player.y=180; player.vy=20;
        stomp.interact(player,100,140,false);
        require(stomp.state==sm63::EnemyState::Squished && player.vy==-8 && player.health==8,"Fast stomp must bounce without hurting Mario");
        for(int i=0;i<11;++i) stomp.tick(terrain,player);
        require(stomp.state==sm63::EnemyState::Gone,"Squish animation must finish");
        sm63::Enemy side(100,190);
        player.reset(); player.x=110; player.y=190;
        side.interact(player,110,190,false);
        require(player.health==7 && player.vx==7 && player.vy==-5 && player.invincibleTicks==90,"Side hit damage and knockback");
        side.interact(player,110,190,false);
        require(player.health==7,"Invulnerability must prevent repeated damage");
        sm63::Enemy dive(100,190);
        player.reset(); player.x=90; player.y=190; player.vx=10; player.diving=true;
        dive.interact(player,90,190,false);
        require(dive.state==sm63::EnemyState::Tumble && dive.vx>0 && player.health==8,"Dive must knock Goomba away without damage");
        sm63::Enemy fastSide(100,190);
        player.reset(); player.x=140; player.y=190;
        fastSide.interact(player,60,190,false);
        require(player.health==7 && player.vx<0,"Fast side crossing must hit and knock back toward approach");
        sm63::Enemy spin(100,190);
        player.reset();player.x=70;player.y=190;player.spinSpeed=15;
        spin.interact(player,70,190,false);
        require(spin.state==sm63::EnemyState::Tumble && spin.vx>0 && player.health==8,"Spin reach must launch Goomba away without damage");
        sm63::Enemy miss(100,190);
        player.reset(); player.x=150; player.y=180; player.vy=20;
        miss.interact(player,150,140,false);
        require(miss.state==sm63::EnemyState::Walking,"Near-miss must not stomp");
        sm63::Enemy pound(100,190);
        player.reset(); player.x=100; player.y=180; player.vy=20; player.pound=sm63::Pound::Falling;
        pound.interact(player,100,140,true);
        require(pound.state==sm63::EnemyState::Squished && player.pound==sm63::Pound::None && player.vy==-10,"Pound must defeat Goomba and clear attack state");
        using K=sm63::EnemyKind;using S=sm63::EnemyState;
        sm63::Enemy water(100,210);
        player.reset();player.x=108;player.y=190;player.fludd.equip(sm63::Nozzle::Hover);player.fludd.spraying=true;
        water.interact(player,108,190,false);
        require(water.state==S::Tumble && water.vx==3 && !water.powerHit && player.health==8,"Hover spray starts a weak knockback");
        water.interact(player,108,190,false);
        require(water.powerHit,"Sustained water builds enough speed to defeat a Goomba");
        sm63::Enemy dry(100,210);player.fludd.spraying=false;dry.interact(player,108,190,false);
        require(dry.state==S::Walking,"Inactive FLUDD cannot hit enemies");
        sm63::Enemy charge(100,190);player.reset();player.x=90;player.y=190;player.vx=10;
        player.fludd.equip(sm63::Nozzle::Turbo);player.fludd.spraying=true;
        charge.interact(player,90,190,false);
        require(charge.state==S::Tumble && player.health==8,"Turbo body contact knocks enemies away safely");
        sm63::Enemy bomb(100,190,K::Bobomb);player.reset();player.x=110;player.y=190;
        bomb.tick(terrain,player);require(bomb.fuse>0,"Bob-omb notices Mario and lights its fuse");
        bomb.fuse=95;bomb.tick(terrain,player);
        require(bomb.state==S::Exploding,"Bob-omb detonates at the end of its fuse");
        player.x=bomb.x;player.y=bomb.y;bomb.interact(player,player.x,player.y,false);
        require(player.health==6,"Explosion inflicts two health points");
        bomb.interact(player,player.x,player.y,false);require(player.health==6,"Explosion respects invulnerability");
        for(int i=0;i<30;++i)bomb.tick(terrain,player);
        require(bomb.state==S::Gone,"Explosion finishes and removes Bob-omb");
        sm63::Enemy contact(100,100,K::Bobomb);player.reset();player.x=90;player.y=100;player.vx=6;
        contact.interact(player,90,100,false);
        require(player.health==8 && player.invincibleTicks==0 && player.vx==-3,"Bob-omb body contact only shoves Mario; no damage or immunity");
        sm63::Terrain impacts;impacts.load(0,0,300,200,std::vector<sm63::level::Span>{});
        impacts.blocks.push_back({140,0,160,150});
        sm63::Enemy thrown(125,100,K::Bobomb);player.reset();player.x=100;player.y=100;player.spinSpeed=15;
        thrown.interact(player,100,100,false);
        require(thrown.powerHit && thrown.state==S::Tumble,"Spin arms a power-hit Bob-omb");
        thrown.tick(impacts,player);
        require(thrown.state==S::Exploding,"Spun Bob-omb detonates on wall impact before fuse expires");
        sm63::Enemy weak(129,100,K::Bobomb);weak.knock(2,0,false);weak.tick(impacts,player);
        require(weak.state!=S::Exploding,"Weak unpowered collision must not trigger a blast");
        impacts.blocks={{0,100,300,150}};
        sm63::Enemy fall(100,98,K::Bobomb);fall.knock(12,8,true);fall.tick(impacts,player);
        require(fall.state==S::Exploding,"Hard powered landing detonates Bob-omb");
        sm63::Enemy koopa(100,190,K::Koopa,1);
        player.reset();player.x=100;player.y=170;player.vy=10;koopa.interact(player,100,150,false);
        require(koopa.state==S::Walking,"Stomping winged Koopa removes wings");
        player.y=170;player.vy=10;koopa.interact(player,100,150,false);
        require(koopa.state==S::Shell,"Second stomp leaves a shell");
        koopa.contactCooldown=0;player.y=190;player.x=90;player.vy=0;koopa.interact(player,90,190,false);
        require(koopa.vx>0 && player.health==8,"Walking into a shell kicks it away");
        sm63::Enemy shy(100,190,K::ShyGuy,1);
        player.reset();player.x=100;player.y=170;player.vy=10;shy.interact(player,100,150,false);
        require(shy.state==S::Walking,"Winged Shy Guy loses flight after a stomp");
        player.y=170;player.vy=10;shy.interact(player,100,150,false);
        require(shy.state==S::Squished,"Grounded Shy Guy can be squished");
        sm63::Enemy bird(100,100,K::Goonie);
        player.reset();player.x=100;player.y=96;player.vy=5;
        bird.interact(player,100,85,false);
        require(bird.riding && player.grounded && player.y==92 && player.health==8,"Goonie is a rideable bird, not a contact hazard");
        sm63::Terrain birdTerrain;birdTerrain.load(0,0,200,200,std::vector<sm63::level::Span>{});
        birdTerrain.blocks.push_back({113,60,116,100});
        sm63::Enemies carrier;carrier.actors.clear();carrier.actors.emplace_back(100,100,K::Goonie);
        player.reset();player.x=125;player.y=96;player.vy=5;
        carrier.tick(birdTerrain,player,125,85,false);
        require(!birdTerrain.body(player.x,player.y) && !carrier.actors[0].riding,"Bird carry must not push Mario through terrain");
        sm63::Enemies blast;blast.actors.clear();blast.actors.emplace_back(100,100,K::Bobomb);blast.actors.emplace_back(120,100);
        blast.actors[0].state=S::Exploding;player.reset();player.x=-100;
        blast.tick(terrain,player,player.x,player.y,false);
        require(blast.actors[1].state==S::Tumble && blast.actors[1].powerHit,"Explosion knocks nearby enemies away");
        enemies.actors.front().state=sm63::EnemyState::Gone;
        enemies.reset();
        require(enemies.actors.front().state==sm63::EnemyState::Walking,"Level reset restores enemies");
        sm63::Enemy penguin(100,100,K::Penguin);player.reset();player.x=112;player.y=100;player.grounded=true;player.vx=-3;
        penguin.interact(player,112,100,false);
        require(player.health==8 && player.vx>0 && player.vy<0,"Penguin contact bumps Mario without damage");
        player.x=100;player.y=78;player.vy=8;player.grounded=false;
        penguin.interact(player,100,65,false);
        require(player.vy==-9 && penguin.state==S::Walking,"Penguin head bounces without squishing");
        player.reset();player.x=125;player.y=100;player.spinSpeed=15;
        penguin.interact(player,125,100,false);
        require(penguin.vx<0 && penguin.state==S::Walking,"Spin shoves a penguin without killing it");
        sm63::Enemy flyer(100,100,K::Penguin,1);player.x=-500;
        for(int i=0;i<20;++i)flyer.tick(terrain,player);
        require(std::abs(flyer.y-100)>1 && flyer.state==S::Flying,"Flying penguin bobs around its source height");
        sm63::Terrain pond;pond.load(0,0,300,300,std::vector<sm63::level::Span>{});
        pond.water.push_back({0,20,300,300,false});
        sm63::Enemy fish(100,100,K::Cheep);player.reset();player.x=140;player.y=117;
        fish.tick(pond,player);
        require(fish.seeing && fish.vx>0 && fish.height()==8,"Hungry Cheep steers toward nearby Mario with source body height");
        sm63::Enemy calmFish(100,100,K::Cheep,1);calmFish.tick(pond,player);
        require(!calmFish.seeing && calmFish.vx<0,"Non-hungry Cheep patrols instead of chasing");
        player.x=fish.x;player.y=fish.y;player.spinSpeed=15;
        fish.interact(player,player.x,player.y,false);
        require(fish.state==S::Tumble && fish.powerHit,"Spin knocks Cheep out of swimming state");
        std::cout << "Enemy terrain, stomp, damage, invulnerability, dive, pound and reset passed\n";
    } catch(const std::exception& e) { std::cerr << e.what() << '\n'; return 1; }
}
